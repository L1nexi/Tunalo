import { expect, test } from "@playwright/test"
import type { Page } from "@playwright/test"
import { mockSetupApi, profile, saveSettings } from "./support/profileApi"

async function openSection(page: Page, name: string): Promise<void> {
  await page.getByRole("navigation", { name: "设置项" }).getByRole("button", { name }).click()
}

test("空活动配置可打开，添加空层跨分类保留且不构成配置修改", async ({ page }) => {
  await mockSetupApi(page, true, { ...profile, activity: null })
  await page.goto("/?locale=zh&test=1")
  await openSection(page, "活动识别")
  await expect(page.getByRole("group", { name: "工作场景规则", exact: true }).getByRole("textbox", { name: "进程名", exact: true })).toBeEmpty()
  await openSection(page, "调度风格")
  for (let index = 0; index < 4; index++) await page.getByRole("button", { name: "添加层级", exact: true }).click()
  await expect(page.getByRole("button", { name: "添加层级", exact: true })).toBeDisabled()
  await expect(page.getByRole("button", { name: "保存并应用", exact: true })).toBeDisabled()
  await openSection(page, "活动识别")
  await openSection(page, "调度风格")
  await expect(page.getByRole("group", { name: "第 4 优先级", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "删除第 4 优先级", exact: true }).click()
  await expect(page.getByRole("button", { name: "添加层级", exact: true })).toBeEnabled()
  await page.getByRole("button", { name: "关闭", exact: true }).click()
  await expect(page.getByRole("alertdialog")).toHaveCount(0)
})

test("拖拽与键盘设置同层偏好，保存过滤空层并在重开后恢复", async ({ page }) => {
  await mockSetupApi(page, true, { ...profile, activity: null })
  await page.goto("/?locale=zh&test=1")
  await openSection(page, "调度风格")
  for (let index = 0; index < 3; index++) await page.getByRole("button", { name: "添加层级", exact: true }).click()
  await page.getByRole("button", { name: "拖动天气", exact: true }).dragTo(page.getByRole("group", { name: "第 1 优先级", exact: true }))
  await page.getByRole("button", { name: "拖动活动", exact: true }).dragTo(page.getByRole("group", { name: "第 2 优先级", exact: true }))
  const moveTime = page.getByRole("combobox", { name: "移动时段到", exact: true })
  await moveTime.focus()
  await moveTime.press("Enter")
  await page.getByRole("option", { name: "第 2 优先级", exact: true }).press("Enter")
  await expect(page.getByRole("group", { name: "第 2 优先级", exact: true }).getByRole("button", { name: "拖动时段", exact: true })).toBeVisible()
  await openSection(page, "查看配置草稿")
  await expect(page.getByText(/^未指定优先级 → 天气 > (活动、时段|时段、活动)$/)).toBeVisible()
  const saved = await saveSettings(page)
  expect(saved.version).toBe(3)
  expect(saved.matching.preference_tiers.map((tier) => new Set(tier))).toEqual([new Set(["weather"]), new Set(["activity", "time"])])
  expect(saved.activity).toEqual({ work_processes: [], leisure_processes: [], work_title_keywords: [], leisure_title_keywords: [] })
  await page.reload()
  await openSection(page, "调度风格")
  await expect(page.getByRole("group", { name: "第 1 优先级", exact: true }).getByRole("button", { name: "拖动天气", exact: true })).toBeVisible()
  await expect(page.getByRole("group", { name: "第 2 优先级", exact: true }).getByRole("button", { name: "拖动活动", exact: true })).toBeVisible()
  await expect(page.getByRole("group", { name: "第 3 优先级", exact: true })).toHaveCount(0)
  await expect(page.getByRole("button", { name: "保存并应用", exact: true })).toBeDisabled()
})

test("移动和删除层级改变优先顺序，删除的变量回到待选区", async ({ page }) => {
  await mockSetupApi(page, true, { ...profile, matching: { preference_tiers: [["weather"], ["activity", "time"]] } })
  await page.goto("/?locale=zh&test=1")
  await openSection(page, "调度风格")
  await page.getByRole("button", { name: "上移第 2 优先级", exact: true }).click()
  expect((await saveSettings(page)).matching.preference_tiers.map((tier) => new Set(tier))).toEqual([new Set(["activity", "time"]), new Set(["weather"])])
  await page.getByRole("button", { name: "删除第 1 优先级", exact: true }).click()
  const unassigned = page.getByRole("group", { name: "未指定优先级", exact: true })
  await expect(unassigned.getByRole("button", { name: "拖动活动", exact: true })).toBeVisible()
  await expect(unassigned.getByRole("button", { name: "拖动时段", exact: true })).toBeVisible()
  expect((await saveSettings(page)).matching.preference_tiers).toEqual([["weather"]])
  await page.getByRole("button", { name: "删除第 1 优先级", exact: true }).click()
  expect((await saveSettings(page)).matching.preference_tiers).toEqual([])
  await page.reload()
  await openSection(page, "调度风格")
  await expect(page.getByRole("group", { name: "未指定优先级", exact: true }).getByRole("button", { name: /^拖动/ })).toHaveCount(4)
})

test("同层变量拖出再放回原层不构成配置修改", async ({ page }) => {
  await mockSetupApi(page, true, { ...profile, matching: { preference_tiers: [["activity", "weather"]] } })
  await page.goto("/?locale=zh&test=1")
  await openSection(page, "调度风格")
  await page.getByRole("button", { name: "拖动天气", exact: true }).dragTo(page.getByRole("group", { name: "未指定优先级", exact: true }))
  await expect(page.getByRole("button", { name: "保存并应用", exact: true })).toBeEnabled()
  await page.getByRole("button", { name: "拖动天气", exact: true }).dragTo(page.getByRole("group", { name: "第 1 优先级", exact: true }))
  await expect(page.getByRole("button", { name: "保存并应用", exact: true })).toBeDisabled()
  await openSection(page, "查看配置草稿")
  await expect(page.getByText("所有修改已保存。", { exact: true })).toBeVisible()
})

test("点击、拖到区域外或按 Escape 取消均保留原有偏好", async ({ page }) => {
  await mockSetupApi(page, true, { ...profile, matching: { preference_tiers: [["weather"], ["activity"]] } })
  await page.goto("/?locale=zh&test=1")
  await openSection(page, "调度风格")
  const weather = page.getByRole("button", { name: "拖动天气", exact: true })
  await weather.click()
  await expect(page.getByRole("button", { name: "保存并应用", exact: true })).toBeDisabled()
  await weather.dragTo(page.getByRole("heading", { name: "调整调度风格", exact: true }))
  await expect(page.getByRole("button", { name: "保存并应用", exact: true })).toBeDisabled()
  await weather.hover()
  await page.mouse.down()
  await page.getByRole("group", { name: "第 2 优先级", exact: true }).hover()
  await page.keyboard.press("Escape")
  await page.mouse.up()
  await expect(page.getByRole("group", { name: "第 1 优先级", exact: true }).getByRole("button", { name: "拖动天气", exact: true })).toBeVisible()
  await expect(page.getByRole("button", { name: "保存并应用", exact: true })).toBeDisabled()
})

test("服务端偏好校验错误定位到可见字段", async ({ page }) => {
  await mockSetupApi(page, true)
  await page.route("**/api/profile", async (route) => {
    if (route.request().method() === "GET") return route.fallback()
    await route.fulfill({ status: 422, json: { error: "invalid_profile", issues: [{ path: ["matching", "preference_tiers", 0, 0], code: "value_error", message: "invalid preference tiers" }] } })
  })
  await page.goto("/?locale=zh&test=1")
  await openSection(page, "调度风格")
  await page.getByRole("button", { name: "添加层级", exact: true }).click()
  await page.getByRole("button", { name: "拖动天气", exact: true }).dragTo(page.getByRole("group", { name: "第 1 优先级", exact: true }))
  await openSection(page, "查看配置草稿")
  await page.getByRole("button", { name: "保存并应用", exact: true }).click()
  await expect(page.getByText("请检查情境偏好，每项情境只能出现一次。", { exact: true })).toBeVisible()
  await expect(page.getByRole("group", { name: "未指定优先级", exact: true })).toBeFocused()
})

test("直接用键盘创建优先级，移动后保留焦点并保存顺序", async ({ page }) => {
  await mockSetupApi(page, true)
  await page.goto("/?locale=zh&test=1")
  await page.getByRole("navigation").getByRole("button", { name: "调度风格", exact: true }).click()
  await expect(page.getByText("不设置优先级时，Tunalo 会综合当前情境选择合适的场景。", { exact: true })).toBeVisible()

  const menu = page.getByRole("combobox", { name: "移动天气到", exact: true })
  await menu.focus()
  await menu.press("Enter")
  await page.getByRole("option", { name: "移到新优先级", exact: true }).press("Enter")
  await expect(page.getByRole("group", { name: "第 1 优先级", exact: true }).getByRole("button", { name: "拖动天气", exact: true })).toBeVisible()
  await expect(menu).toBeFocused()

  expect((await saveSettings(page)).matching.preference_tiers).toEqual([["weather"]])
})
